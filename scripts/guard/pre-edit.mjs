#!/usr/bin/env node
// PreToolUse hook for Edit/Write/MultiEdit: blocks writes the repo forbids before they land.
//
// Reads the hook JSON on stdin. A block writes one line to stderr as `rule-id: message` and exits 2;
// clean or unparseable input allows silently with exit 0. The decision lives in checkEdit() so unit
// tests can call it directly. Blocks: writes under the generated ios/ and android/ trees, and newly
// added eslint-disable or `design-ignore:` markers that carry no reason. Node 18+, built-ins only.

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const CNG = 'rn-native-deps/no-native-edits: ios/ and android/ are generated by expo prebuild. Change app.config.ts or a config plugin instead.';
const ESLINT_REASON = 'eslint-comments/require-description: add a reason after --, e.g. // eslint-disable-next-line no-console -- debug output for CI';
const DESIGN_REASON = 'design/ignore-reason: write design-ignore: <reason>.';
const CODE_FILE = /\.(ts|tsx|js|mjs|cjs)$/;

// Patterns are assembled at runtime so this hook's own source never contains a bare directive: once
// the hook is wired up, editing it must not be blocked by itself.
const L = '/';
const OPEN = `(?:${L}${L}|${L}\\*)`; // a // line comment or a /* opener
const DGN = ['design', '-ignore'].join('');
const DIRECTIVE_SOURCE = `${OPEN}[ \\t]*(eslint-disable(?:-line|-next-line)?\\b[\\s\\S]*?)(?:\\*\\/|$)`;

// A directive needs its rules at the front, then a reason after `--`.
function hasReason(body) {
  const cut = body.indexOf('--');
  return cut !== -1 && body.slice(cut + 2).trim().length > 0;
}

// eslint-disable directives on one line, scanning every // or /* occurrence, not just the first.
function directives(line) {
  const out = [];
  const re = new RegExp(DIRECTIVE_SOURCE, 'g');
  let m;
  while ((m = re.exec(line))) {
    out.push({ text: m[0].trim(), ok: hasReason(m[1]) });
  }
  return out;
}

// The design-skip marker only silences design/check.mjs when it states its reason: design-ignore: <reason>.
function designDirective(line) {
  const at = line.indexOf(DGN);
  if (at === -1) return null;
  const after = line.slice(at + DGN.length);
  return { text: line.trim(), ok: /^[ \t]*:[ \t]*\S/.test(after) };
}

// The file path relative to the repo root, or null when it sits outside the repo.
function relPath(repoRoot, filePath) {
  const abs = path.isAbsolute(filePath) ? path.normalize(filePath) : path.resolve(repoRoot, filePath);
  const rel = path.relative(path.normalize(repoRoot), abs);
  if (!rel || rel === '..' || rel.split(path.sep)[0] === '..') return null;
  return rel.split(path.sep).join('/');
}

// (old, new) text pairs for one tool input; Write compares against the file on disk, the edit tools
// against the text each edit replaces.
function pairsFor(toolName, toolInput, filePath) {
  if (toolName === 'Write') {
    return [[readIfExists(filePath), typeof toolInput.content === 'string' ? toolInput.content : '']];
  }
  if (toolName === 'Edit') {
    return [[typeof toolInput.old_string === 'string' ? toolInput.old_string : '', typeof toolInput.new_string === 'string' ? toolInput.new_string : '']];
  }
  if (toolName === 'MultiEdit') {
    return (Array.isArray(toolInput.edits) ? toolInput.edits : [])
      .map((edit) => [typeof edit.old_string === 'string' ? edit.old_string : '', typeof edit.new_string === 'string' ? edit.new_string : '']);
  }
  return [];
}

function readIfExists(filePath) {
  try {
    return fs.readFileSync(filePath, 'utf8');
  } catch {
    return '';
  }
}

// The decision: one stderr line for the first violated rule, or null to allow.
export function checkEdit(toolName, toolInput, repoRoot) {
  if (!toolInput || typeof toolInput.file_path !== 'string' || !repoRoot) return null;
  const rel = relPath(repoRoot, toolInput.file_path);
  if (rel && (rel === 'ios' || rel === 'android' || rel.startsWith('ios/') || rel.startsWith('android/'))) return CNG;
  if (!CODE_FILE.test(rel ? rel : toolInput.file_path)) return null;
  const filePath = path.isAbsolute(toolInput.file_path) ? path.normalize(toolInput.file_path) : path.resolve(repoRoot, toolInput.file_path);
  for (const [oldText, newText] of pairsFor(toolName, toolInput, filePath)) {
    if (!newText) continue;
    for (const line of newText.split('\n')) {
      for (const directive of directives(line)) {
        if (directive.ok) continue;
        if (oldText && oldText.includes(directive.text)) continue; // already there, not newly added
        return ESLINT_REASON;
      }
      const design = designDirective(line);
      if (design && !design.ok && !(oldText && oldText.includes(design.text))) return DESIGN_REASON;
    }
  }
  return null;
}

// The repo that owns the file: `git rev-parse --show-toplevel` in the hook's cwd, or the cwd itself.
function gitRoot(cwd) {
  try {
    const r = spawnSync('git', ['rev-parse', '--show-toplevel'], { cwd, encoding: 'utf8' });
    const out = String((r && r.stdout) || '').trim();
    if (r && r.status === 0 && out) return out;
  } catch { /* no git on PATH: fall back to the cwd */ }
  return cwd;
}

function main() {
  let hook;
  try {
    hook = JSON.parse(fs.readFileSync(0, 'utf8'));
  } catch {
    return 0; // a hook cannot judge input it cannot parse; allow
  }
  if (!hook || !hook.tool_input) return 0;
  const cwd = typeof hook.cwd === 'string' && hook.cwd ? hook.cwd : process.cwd();
  const verdict = checkEdit(hook.tool_name, hook.tool_input, gitRoot(cwd));
  if (!verdict) return 0;
  fs.writeSync(2, `${verdict}\n`);
  return 2;
}

const isMain = Boolean(process.argv[1]) && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) process.exit(main());